/** Every cut scene, from the ONE list the 3D Scene Editor shows (lib/star/cutscene/sceneList.ts):
 *  the hand-made scenes with a real still, then every scene kept from the Scene generator.
 *  Tap one: it opens in the editor. */
function CutScenes() {
  const [kept, setKept] = useState<KeptScene[]>([]);
  const [loaded, setLoaded] = useState(false);
  useEffect(() => {
    setKept(loadKeptLocal());
    fetchKeptScenes().then((k) => { setKept(k); setLoaded(true); });
  }, []);
  const list = cutsceneList(kept);
  return (
    <div>
      <div className="a3-cuts">
        {list.map((c) => (
          <Link key={c.id} href={c.href} data-cut={c.id} className="a3-card">
            <div className="a3-pic a3-cutpic" style={c.still ? { backgroundImage: `url(${c.still})` } : undefined}>
              {!c.still && <span className="a3-kept">KEPT</span>}
            </div>
            <div className="a3-cf"><b>{c.name}</b><span className="a3-play">EDIT</span></div>
          </Link>
        ))}
      </div>
      <div className="a3-note">
        The same list as the 3D Scene Editor&apos;s scene buttons: {list.filter((c) => c.kind === "hand").length} hand-made
        {" "}and {kept.length} kept from the Scene generator{loaded ? "" : " (checking for more…)"}. Tap one to open it in the editor.
      </div>
    </div>
  );
}

type Tab = "places" | "cuts" | "scenes" | "assets";
const TAB_KEY = "star-3d-area-tab";

export default function Area3dPage() {
  const [tab, setTabState] = useState<Tab>("places");
  useEffect(() => {
    try { const t = localStorage.getItem(TAB_KEY); if (t === "places" || t === "cuts" || t === "scenes" || t === "assets") setTabState(t); } catch { /* no storage */ }
  }, []);
  const setTab = (t: Tab) => { setTabState(t); try { localStorage.setItem(TAB_KEY, t); } catch { /* no storage */ } };
  const tabs: [Tab, string][] = [["places", `Places (${PLACES.length})`], ["cuts", "Cut scenes"], ["scenes", `Other scenes (${SCENES_3D.length})`], ["assets", "3D files"]];
  return (
    <BroadcastPage title="3D Area" sub="Every 3D place, every cut scene, plus the 3D file store.">
      <div className="a3-layout">
        <nav className="a3-rail">
          {tabs.map(([t, label]) => (
            <button key={t} data-tab={t} aria-pressed={tab === t} className="a3-tab" onClick={() => setTab(t)}>{label}</button>
          ))}
        </nav>
        <div className="a3-main">
          {tab === "places" && (
            <div className="a3-cards">
              {PLACES.map((pl) => (
                <Link key={pl.id} href={pl.href} data-place={pl.id} className="a3-card">
                  <div className="a3-pic" style={{ backgroundImage: `url(/admin/3d-area/${pl.id}.webp)` }} />
                  <div className="a3-cf"><b>{pl.title}</b><span className="a3-play">PLAY</span></div>
                </Link>
              ))}
            </div>
          )}
          {tab === "cuts" && <CutScenes />}
          {tab === "scenes" && <div className="a3-panel a3-scenes">{SCENES_3D.map((s) => <SceneCard key={s.id} s={s} />)}</div>}
          {tab === "assets" && <div className="a3-panel"><AssetStore /></div>}
        </div>
      </div>
      <PageGuide page="/star-3d-area-dev" />
    </BroadcastPage>
  );
}
