// Writes lib/star/three3d/assetVersions.ts: a short content hash for every
// file under public/star/ that the 3D scenes load (models, pictures, the
// decoders). lib/star/three3d/assetVersions.ts's loader hook asks for
// /star/x.glb?v=<hash>, and next.config.mjs answers any /star file asked for
// with ?v= as "keep for a year, never ask again" — so a second visit opens a
// 3D place with no network at all, and a changed file has a new hash, so
// nobody keeps an old copy. (Speed job B, 9 Oct 2026.)
//
// next.config.mjs runs this at the start of every build and dev server, so
// the deployed list always matches the deployed files. Run it by hand after
// changing a file if you want the committed copy tidy:
//   node scripts/perf3d/asset-versions.mjs          (write)
//   node scripts/perf3d/asset-versions.mjs --check  (exit 1 if out of date)
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const pub = path.join(root, "public");
const OUT = path.join(root, "lib/star/three3d/assetVersions.ts");
/** What the 3D loaders fetch. shop2d (React <img>) and the app icons are left out. */
const EXT = new Set([".glb", ".gltf", ".bin", ".hdr", ".ktx2", ".webp", ".png", ".jpg", ".wasm", ".js", ".cube", ".json"]);
const SKIP = /^\/star\/(shop2d|app-icon)/;

export function buildAssetVersions() {
  const out = {};
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const f = path.join(dir, e.name);
      if (e.isDirectory()) { walk(f); continue; }
      if (!EXT.has(path.extname(e.name).toLowerCase())) continue;
      const url = "/" + path.relative(pub, f).split(path.sep).join("/");
      if (SKIP.test(url)) continue;
      out[url] = crypto.createHash("sha1").update(fs.readFileSync(f)).digest("hex").slice(0, 8);
    }
  };
  walk(path.join(pub, "star"));
  const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
  return `// GENERATED by scripts/perf3d/asset-versions.mjs (also run by next.config.mjs at every build) — do not edit.\n` +
    `// A short content hash per 3D file: the loaders ask for /star/x?v=<hash>, which the site serves as immutable.\n` +
    `export const ASSET_VERSIONS: Record<string, string> = {\n${body}\n};\n`;
}

/** Write the file if it changed. Returns true when it was out of date. */
export function writeAssetVersions() {
  const text = buildAssetVersions();
  let old = "";
  try { old = fs.readFileSync(OUT, "utf8"); } catch { /* new */ }
  if (old === text) return false;
  fs.writeFileSync(OUT, text);
  return true;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    let old = "";
    try { old = fs.readFileSync(OUT, "utf8"); } catch { /* none */ }
    if (old !== buildAssetVersions()) { console.error("lib/star/three3d/assetVersions.ts is out of date: node scripts/perf3d/asset-versions.mjs"); process.exit(1); }
    console.log("asset versions up to date");
  } else {
    console.log(writeAssetVersions() ? "wrote lib/star/three3d/assetVersions.ts" : "asset versions already up to date");
  }
}
