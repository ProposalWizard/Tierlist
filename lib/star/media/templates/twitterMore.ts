type Spec = Omit<Template, "id" | "archetype" | "persona">;

function bank(persona: string, archetype: Archetype, specs: Spec[]): Template[] {
  return specs.map((s, i) => ({ ...s, id: `ft-${persona}-v2-${i + 1}`, archetype, persona }));
}

