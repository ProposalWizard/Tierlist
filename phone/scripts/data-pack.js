/**
 * phone/scripts/data-pack.js — PUT THE PACKED APP'S DATA INSIDE THE PHONE APP.
 *
 *   node phone/scripts/data-pack.js [--force]      (also run by metro.config.js)
 *
 * The packed Android app (mobile/) carries every club's real squad, the
 * settings and every picture in mobile/packed/ (made by
 * mobile/scripts/pack.mts; read mobile/README.md). The phone app gives the
 * game the SAME answers from the SAME files. This script copies them in:
 *
 *   mobile/packed/data/*.json  → phone/src/data/generated/json/   (in the JS bundle, read on first use)
 *   mobile/packed/img/*        → phone/assets/packed/img/          (app pictures)
 *   public/<fake faces>.png    → phone/assets/packed/faces/        (the default faces)
 *   + phone/src/data/generated/packedData.js and packedImages.js: the lists
 *     phone/src/data/packed.ts reads (fixed `require`s, so the bundler finds them).
 *
 * Everything it writes is generated and git-ignored. Where the packed files
 * are: $KIB_PACKED_DIR, else <repo>/mobile/packed, else the first
 * mobile/packed/ above the repo (a worktree inside the main checkout).
 * With none, it writes EMPTY lists (and says so): the app still builds, and
 * every club falls back to invented players, as the website does without its
 * database. Skips the copy when the output already matches the source.
 */
const fs = require("fs");
const path = require("path");

const PHONE = path.resolve(__dirname, "..");
const REPO = path.resolve(PHONE, "..");
const GEN = path.join(PHONE, "src/data/generated");
const ASSETS = path.join(PHONE, "assets/packed");
const VERSION = 1; // raise when the output's shape changes

function findSource() {
  const cands = [];
  if (process.env.KIB_PACKED_DIR) cands.push(path.resolve(process.env.KIB_PACKED_DIR));
  cands.push(path.join(REPO, "mobile/packed"));
  for (let d = path.dirname(REPO); d !== path.dirname(d); d = path.dirname(d)) cands.push(path.join(d, "mobile/packed"));
  return cands.find((d) => fs.existsSync(path.join(d, "index.json"))) || null;
}

/** "/packed/data/x.json" → its file in the source folder. */
const srcFile = (src, packedPath) => path.join(src, packedPath.replace(/^\/packed\//, ""));

/** The website's fake faces (lib/star/fakeFaces.ts FAKE_FACES), read from that file. */
function fakeFaces() {
  try {
    const ts = fs.readFileSync(path.join(REPO, "lib/star/fakeFaces.ts"), "utf8");
    const block = ts.slice(ts.indexOf("FAKE_FACES"), ts.indexOf("];", ts.indexOf("FAKE_FACES")));
    return [...block.matchAll(/"(\/[^"]+\.(?:png|webp|jpg))"/g)].map((m) => m[1]);
  } catch { return []; }
}

function writeEmpty(why) {
  fs.mkdirSync(GEN, { recursive: true });
  const note = `// Generated by phone/scripts/data-pack.js: NO packed data (${why}).\n`;
  fs.writeFileSync(path.join(GEN, "packedData.js"), note + "module.exports = null;\n");
  fs.writeFileSync(path.join(GEN, "packedImages.js"), note + "module.exports = {};\n");
  fs.writeFileSync(path.join(GEN, "stamp.json"), JSON.stringify({ version: VERSION, packedAt: null }));
}

const rel = (fromDir, file) => {
  const r = path.relative(fromDir, file).split(path.sep).join("/");
  return r.startsWith(".") ? r : "./" + r;
};
const q = JSON.stringify;

function ensurePacked({ force = false, quiet = false } = {}) {
  const say = (s) => { if (!quiet) console.log(`[data-pack] ${s}`); };
  const src = findSource();
  if (!src) {
    const stamp = path.join(GEN, "stamp.json");
    if (!force && fs.existsSync(stamp) && fs.existsSync(path.join(GEN, "packedData.js"))) return { ok: false, reason: "no source (kept the last copy)" };
    writeEmpty("mobile/packed/ not found");
    console.warn("[data-pack] mobile/packed/ not found: the phone app will have NO real squads or photos. Run mobile/scripts/pack.mts (mobile/README.md) or set KIB_PACKED_DIR.");
    return { ok: false, reason: "no source" };
  }
  const index = JSON.parse(fs.readFileSync(path.join(src, "index.json"), "utf8"));
  const faces = fakeFaces();
  const stampWant = { version: VERSION, packedAt: index.packedAt, year: index.year, images: Object.keys(index.images).length, faces: faces.length };
  try {
    const have = JSON.parse(fs.readFileSync(path.join(GEN, "stamp.json"), "utf8"));
    if (!force && q(have) === q(stampWant) && fs.existsSync(path.join(GEN, "packedImages.js"))) return { ok: true, skipped: true, src };
  } catch { /* first run */ }

  say(`copying ${src} (packed ${index.packedAt})`);
  fs.rmSync(GEN, { recursive: true, force: true });
  fs.rmSync(ASSETS, { recursive: true, force: true });
  const JSON_DIR = path.join(GEN, "json");
  fs.mkdirSync(JSON_DIR, { recursive: true });

  // ── Data: one module per packed file, required only when first asked ──
  const copied = new Map(); // packed path → generated file
  const copyJson = (packedPath) => {
    if (copied.has(packedPath)) return copied.get(packedPath);
    const from = srcFile(src, packedPath);
    const to = path.join(JSON_DIR, packedPath.replace(/^\/packed\/data\//, "").replace(/\//g, "-"));
    fs.copyFileSync(from, to);
    copied.set(packedPath, to);
    return to;
  };
  const thunk = (packedPath) => `() => require(${q(rel(GEN, copyJson(packedPath)))})`;
  const map = (obj) => "{\n" + Object.entries(obj).map(([k, v]) => `    ${q(k)}: ${thunk(v)},`).join("\n") + "\n  }";
  const data = [
    "// Generated by phone/scripts/data-pack.js from mobile/packed/ — do not edit, not committed.",
    "/* eslint-disable */",
    "module.exports = {",
    `  packedAt: ${q(index.packedAt)},`,
    `  year: ${q(index.year)},`,
    `  squads: ${thunk(index.squads)},`,
    `  rosters: ${map(index.rosters)},`,
    `  routes: ${map(index.routes)},`,
    `  tables: ${map(index.supabase)},`,
    "};",
    "",
  ].join("\n");
  fs.writeFileSync(path.join(GEN, "packedData.js"), data);

  // ── Pictures: every packed picture, plus the default faces ──
  const IMG = path.join(ASSETS, "img");
  const FACES = path.join(ASSETS, "faces");
  fs.mkdirSync(IMG, { recursive: true });
  fs.mkdirSync(FACES, { recursive: true });
  const lines = [];
  let bytes = 0, missing = 0;
  for (const [url, packedPath] of Object.entries(index.images)) {
    const from = srcFile(src, packedPath);
    if (!fs.existsSync(from)) { missing++; continue; }
    const to = path.join(IMG, path.basename(packedPath));
    if (!fs.existsSync(to)) { fs.copyFileSync(from, to); bytes += fs.statSync(to).size; }
    lines.push(`  ${q(url)}: require(${q(rel(GEN, to))}),`);
  }
  faces.forEach((site, i) => {
    const from = path.join(REPO, "public", site);
    if (!fs.existsSync(from)) { missing++; return; }
    // Android picture names allow only a-z, 0-9 and _: the website's names have spaces and commas.
    const to = path.join(FACES, `fake_face_${i}${path.extname(site).toLowerCase()}`);
    fs.copyFileSync(from, to); bytes += fs.statSync(to).size;
    lines.push(`  ${q(site)}: require(${q(rel(GEN, to))}),`);
  });
  fs.writeFileSync(path.join(GEN, "packedImages.js"), [
    "// Generated by phone/scripts/data-pack.js from mobile/packed/ — do not edit, not committed.",
    "// Picture address (as the game stores it) → the app's bundled copy.",
    "/* eslint-disable */",
    "module.exports = {",
    ...lines,
    "};",
    "",
  ].join("\n"));
  fs.writeFileSync(path.join(GEN, "stamp.json"), JSON.stringify(stampWant));

  const jsonBytes = [...copied.values()].reduce((n, f) => n + fs.statSync(f).size, 0);
  say(`data ${(jsonBytes / 1e6).toFixed(1)} MB in ${copied.size} files; pictures ${(bytes / 1e6).toFixed(1)} MB in ${lines.length}${missing ? ` (${missing} missing)` : ""}`);
  return { ok: true, src, jsonBytes, imageBytes: bytes, images: lines.length };
}

module.exports = { ensurePacked };

if (require.main === module) {
  const r = ensurePacked({ force: process.argv.includes("--force") });
  if (r.skipped) console.log("[data-pack] already up to date");
}
